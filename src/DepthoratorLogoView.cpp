DepthoratorLogoView::DepthoratorLogoView(const VSTGUI::CRect& size)
: VSTGUI::CView(size) {
    setTransparency(true);
    setMouseEnabled(false);
}

void DepthoratorLogoView::draw(VSTGUI::CDrawContext* context) {
    const auto& r = getViewSize();
    const double sx = r.getWidth() / 78.0;
    const double sy = r.getHeight() / 36.0;
    const VSTGUI::CColor white(232, 233, 236, 255);
    const VSTGUI::CColor red(220, 18, 28, 255);

    context->setDrawMode(VSTGUI::kAliasing);
    for (const auto& run : kRuns) {
        context->setFillColor(run.color == 2 ? red : white);
        VSTGUI::CRect rr(r.left + run.x * sx,
                         r.top + run.y * sy,
                         r.left + (run.x + run.w) * sx,
                         r.top + (run.y + 1) * sy);
        context->drawRect(rr, VSTGUI::kDrawFilled);
    }
    setDirty(false);
}

